async (page) => {
  const button = (name) => page.getByRole('button', { name, exact: true });
  const idle = () => page.getByText('就绪', { exact: true }).waitFor();
  await button('数据').click();
  await button('customers').click();
  await page.getByRole('gridcell', { name: '第 1 行 name 林晓·编辑验证', exact: true }).waitFor();
  await page.getByRole('gridcell', { name: '第 1 行 city 杭州', exact: true }).click();
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.evaluate(() => navigator.clipboard.writeText('深圳\tactive\n北京\tpending'));
  await page.keyboard.press('Control+v');
  await page.getByRole('gridcell', { name: '第 1 行 city 深圳', exact: true }).waitFor();
  await page.getByRole('gridcell', { name: '第 2 行 status pending', exact: true }).waitFor();
  await button('应用修改 (2)').click();
  await idle();
  await button('撤销数据库修改').click();
  await page.getByRole('gridcell', { name: '第 1 行 city 杭州', exact: true }).waitFor();
  await idle();
  await page.getByRole('gridcell', { name: '第 1 行 city 杭州', exact: true }).click();
  await page.keyboard.press('Control+c');
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  if (clipboard !== '杭州') throw new Error('Database cell copy failed');
  await button('外观设置').click();
  await page.getByLabel('数据库网格行高', { exact: true }).fill('48');
  await page.getByLabel('数据库背景预设', { exact: true }).selectOption('#1e2521');
  await idle();
  const firstCell = page.getByRole('gridcell', { name: '第 1 行 id 1', exact: true });
  const rowBox = await firstCell.boundingBox();
  if (Math.abs(rowBox.height - 48) > 1) throw new Error('Custom row height was not applied');
  const header = page.getByRole('columnheader', { name: 'name', exact: true });
  const before = await header.boundingBox();
  const resize = await page.getByRole('separator', { name: '调整 name 列宽', exact: true }).boundingBox();
  await page.mouse.move(resize.x + resize.width / 2, resize.y + resize.height / 2);
  await page.mouse.down();
  await page.mouse.move(resize.x + resize.width / 2 + 85, resize.y + resize.height / 2, { steps: 7 });
  await page.mouse.up();
  const after = await header.boundingBox();
  if (Math.abs(after.width - before.width - 85) > 2) throw new Error('Column resize did not follow the pointer');
  await page.emulateMedia({ colorScheme: 'light' });
  const background = () => page.locator('main.database-app').evaluate((el) => getComputedStyle(el).getPropertyValue('--surface').trim());
  if (await background() !== '#1e2521') throw new Error('Database background followed the system theme');
  await page.screenshot({ path: 'output/playwright/database-dark.png' });
  await page.reload();
  await firstCell.waitFor();
  await idle();
  const restoredRow = await firstCell.boundingBox();
  const restoredHeader = await header.boundingBox();
  if (Math.abs(restoredRow.height - 48) > 1 || Math.abs(restoredHeader.width - after.width) > 1) throw new Error('Grid dimensions did not persist');
  if (await background() !== '#1e2521') throw new Error('Background did not persist');
  await button('外观设置').click();
  await page.getByLabel('数据库背景预设', { exact: true }).selectOption('#fff9ed');
  await page.getByLabel('数据库网格行高', { exact: true }).fill('36');
  await button('关闭外观设置').click();
  await page.setViewportSize({ width: 1040, height: 780 });
  await page.screenshot({ path: 'output/playwright/database-compact.png' });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error('Database layout overflows the viewport');
  await page.setViewportSize({ width: 1536, height: 960 });
  await button('外观设置').click();
  await page.getByLabel('数据库背景预设', { exact: true }).selectOption('#ffffff');
  await page.getByLabel('数据库网格行高', { exact: true }).fill('32');
  await button('关闭外观设置').click();
  console.log('PASS database browser: clipboard editing, row height, column resizing, dimension persistence, independent dark background and compact layout');
}
