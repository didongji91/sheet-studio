async (page) => {
  const button = (name) => page.getByRole('button', { name, exact: true });
  const idle = () => page.getByText('就绪', { exact: true }).waitFor();
  const runButton = page.getByRole('button', { name: /^执行 SQL/ });
  await button('SQL 编辑器').click();
  const editor = page.getByLabel('SQL 编辑器', { exact: true });
  await editor.fill('select count(*) as customer_count from customers;\nselect id,name from products order by id;');
  await button('格式化').click();
  if (!(await editor.innerText()).includes('SELECT')) throw new Error('SQL formatting failed');
  await runButton.click();
  await page.getByRole('gridcell', { name: '第 1 行 customer_count 137', exact: true }).waitFor();
  await page.getByRole('button', { name: /^结果 2/ }).click();
  await page.getByRole('gridcell', { name: '第 1 行 name 专业版订阅', exact: true }).waitFor();
  await page.getByRole('button', { name: /^历史 / }).click();
  await page.getByRole('heading', { name: 'SQL 执行历史', exact: false }).waitFor();
  await page.screenshot({ path: 'output/playwright/database-sql.png' });
  await button('关闭 SQL 历史').click();
  await editor.fill('SELECT 17 AS selected_value;\nSELECT 29 AS unselected_value;');
  await editor.press('Control+Home');
  await editor.press('Shift+End');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await editor.press('Control+c');
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  if (copied !== 'SELECT 17 AS selected_value;') throw new Error('SQL copy was intercepted: ' + copied);
  await editor.press('Control+Enter');
  await page.getByRole('gridcell', { name: '第 1 行 selected_value 17', exact: true }).waitFor();
  if (await page.getByRole('button', { name: /^结果 2/ }).count()) throw new Error('SQL selection executed extra statements');
  await idle();
  await editor.fill('SELECT * FROM table_does_not_exist;');
  await runButton.click();
  await page.getByRole('alert').filter({ hasText: 'no such table' }).waitFor();
  await button('关闭数据库错误').click();
  await editor.fill('WITH RECURSIVE n(x) AS (VALUES(1) UNION ALL SELECT x+1 FROM n) SELECT SUM(x) FROM n;');
  await editor.press('Control+Enter');
  await editor.press('Control+Enter');
  if (!(await runButton.isDisabled())) throw new Error('Repeated Ctrl+Enter cleared the query busy state');
  await button('取消').click();
  await page.getByRole('alert').filter({ hasText: '取消' }).waitFor();
  await idle();
  await editor.fill('SELECT 7 AS recovered;');
  await runButton.click();
  await page.getByRole('gridcell', { name: '第 1 行 recovered 7', exact: true }).waitFor();
  await idle();
  await editor.fill("CREATE TABLE ui_sql_check(id INTEGER PRIMARY KEY, name TEXT); INSERT INTO ui_sql_check VALUES(1,'SQL 新记录');");
  await runButton.click();
  await button('ui_sql_check').waitFor();
  await idle();
  await button('ui_sql_check').click();
  await page.getByRole('gridcell', { name: '第 1 行 name SQL 新记录', exact: true }).waitFor();
  await button('SQL 编辑器').click();
  await editor.fill('DROP TABLE ui_sql_check;');
  await runButton.click();
  await button('ui_sql_check').waitFor({ state: 'detached' });
  await idle();
  if (await page.getByRole('alert').count()) throw new Error('Dropping the selected table left a stale-table error');
  await editor.fill("SELECT id, name, NULL AS empty_value, X'00ff' AS binary_value FROM customers ORDER BY id LIMIT 3;");
  await runButton.click();
  await page.getByRole('gridcell', { name: '第 1 行 name 林晓·编辑验证', exact: true }).waitFor();
  await idle();
  for (const format of ['CSV', 'JSON', 'XLSX']) {
    await button(format).click();
    await idle();
    if (await page.getByRole('alert').count()) throw new Error(format + ' export failed');
  }
  await page.getByLabel('导出数据库', { exact: true }).selectOption('db');
  await idle();
  await page.getByLabel('导出数据库', { exact: true }).selectOption('sql');
  await idle();
  console.log('PASS database SQL browser: formatting, multiple results, history, selection, SQL clipboard, errors, cancellation and recovery, CREATE/DROP, CSV/JSON/XLSX and full SQLite exports');
}
